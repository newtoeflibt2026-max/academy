$path="C:\Users\nelt2\yamen_academy\app.py"
$ts=Get-Date -Format "yyyyMMdd_HHmmss"
Copy-Item $path "$path.bak_emojifix_$ts"
$b=[System.IO.File]::ReadAllBytes($path)
Write-Host "orig size: $($b.Length)"
$pairs=@(
 ,@(@(0xC3,0xB0,0xC2,0x9F,0xC2,0x92,0xC2,0xB3),@(0xF0,0x9F,0x92,0xB3))
 ,@(@(0xC3,0xB0,0xC2,0x9F,0xC2,0x91,0xC2,0xA4),@(0xF0,0x9F,0x91,0xA4))
 ,@(@(0xC3,0xB0,0xC2,0x9F,0xC2,0x93,0xC2,0x9B),@(0xF0,0x9F,0x93,0x9B))
 ,@(@(0xC3,0xB0,0xC2,0x9F,0xC2,0x93,0xC2,0xB1),@(0xF0,0x9F,0x93,0xB1))
 ,@(@(0xC3,0xB0,0xC2,0x9F,0xC2,0x93,0xC2,0xA6),@(0xF0,0x9F,0x93,0xA6))
 ,@(@(0xC3,0xB0,0xC2,0x9F,0xC2,0x92,0xC2,0xB0),@(0xF0,0x9F,0x92,0xB0))
 ,@(@(0xC3,0xB0,0xC2,0x9F,0xC2,0x86,0xC2,0x94),@(0xF0,0x9F,0x86,0x94))
)
$out=New-Object System.Collections.Generic.List[byte]
$i=0; $total=0
while($i -lt $b.Length){
  $hit=$null
  foreach($p in $pairs){
    $ndl=$p[0]
    if($i+$ndl.Length -le $b.Length){
      $ok=$true
      for($j=0;$j -lt $ndl.Length;$j++){ if($b[$i+$j] -ne $ndl[$j]){ $ok=$false; break } }
      if($ok){ $hit=$p; break }
    }
  }
  if($hit){ foreach($x in $hit[1]){ $out.Add([byte]$x) }; $i+=$hit[0].Length; $total++ }
  else { $out.Add($b[$i]); $i++ }
}
Write-Host "replacements: $total"
if($total -ge 6){
  [System.IO.File]::WriteAllBytes($path,$out.ToArray())
  Write-Host "new size: $((Get-Item $path).Length)"
  py -m py_compile $path
  if($LASTEXITCODE -eq 0){ Write-Host "[OK] syntax valid" }
  else { Write-Host "[FAIL] restoring"; Copy-Item "$path.bak_emojifix_$ts" $path -Force }
} else {
  Write-Host "[ABORT] too few replacements"
  Copy-Item "$path.bak_emojifix_$ts" $path -Force
}
